import type {
  MediaFault,
  PlaybackSourceChoice,
  RecordingSources,
  Track,
} from "../src/types.ts";

export type LegacyFacts = {
  chosen: PlaybackSourceChoice;
  deviceFault: MediaFault | undefined;
  /** The track's row in `localDB.downloads`, or undefined. */
  download: object | undefined;
  online: boolean;
  recentFailure: boolean;
  sources: RecordingSources;
  track: Pick<Track, "id" | "serverAvailable" | "sourceType">;
};

export type Shown = "device" | "server" | "torbox" | "remote";

// What `load` does once `offlineUrl` has answered (complete copy or not).
export type LegacyLoad =
  | { error: string }
  | { plays: "device"; show: "device"; notice: "server" | "original" | null }
  | {
      plays: "stream";
      /** `?source=` on the media URL; "" for automatic. */
      query: string;
      show: Shown;
      /** `?source=` on the location request. */
      location: "auto" | "server" | "original";
      /** The explicit stream load that may switch to the device copy. */
      streamLoad: null | {
        request: "server" | "original";
        /** A stall checks the connection and may switch (true) or surfaces an error (false). */
        deviceCopy: boolean;
      };
    };

export type LegacyOutcome = {
  /** The sources come from the cache, refreshed in the background. */
  sourcesFromCache: boolean;
  result:
    | { error: string }
    | {
        preference: PlaybackSourceChoice;
        /** `load` asks `offlineUrl` for the device copy. */
        looksForDevice: boolean;
        complete: LegacyLoad;
        incomplete: LegacyLoad;
        /** `input.bad(source)` for each shown source and for none. */
        faulty: Record<Shown | "none", boolean>;
      };
};

const offlinePreference = (
  chosen: PlaybackSourceChoice,
  online: boolean,
  download: unknown,
  fault: unknown,
): PlaybackSourceChoice =>
  !online && (chosen === "server" || chosen === "original") && download && !fault
    ? "device"
    : chosen;
const canFallBackToDevice = (request: string, download: unknown, fault: unknown) =>
  (request === "server" || request === "original") && !!download && !fault;
const skipStream = (input: {
  request: string;
  recentFailure: boolean;
  download: unknown;
  fault: unknown;
}) => input.recentFailure && canFallBackToDevice(input.request, input.download, input.fault);

export function legacyOutcome(facts: LegacyFacts): LegacyOutcome {
  const { chosen, recentFailure, download, track } = facts;
  const fault = facts.deviceFault;
  const skipping =
    (chosen === "server" || chosen === "original") &&
    skipStream({ request: chosen, recentFailure, download, fault });
  const state = facts.sources;
  const preference = offlinePreference(chosen, facts.online, download, fault);
  const refuse = (error: string): LegacyOutcome => ({
    sourcesFromCache: skipping,
    result: { error },
  });
  if (state.faults.recording)
    return refuse(
      "This recording is marked faulty. Open Versions & sources to choose another recording or clear its flag.",
    );
  const available = state.tracks.find((item) => item.id === track.id) || {
    server: track.serverAvailable || track.sourceType === "local",
    original: track.sourceType !== "local",
  };
  const server = available.server && !state.faults.server,
    original = available.original && !state.faults.original;
  if (preference === "device" && (!download || fault))
    return refuse(
      "This device copy is missing or marked faulty. Choose another source in Versions & sources.",
    );
  if (preference === "server" && !server)
    return refuse(
      "This server copy is missing or marked faulty. Choose another source in Versions & sources.",
    );
  if (preference === "original" && !original)
    return refuse(
      "The original stream is unavailable or marked faulty. Choose another source in Versions & sources.",
    );
  if (preference === "auto" && (!download || fault) && !server && !original)
    return refuse(
      "No healthy audio source is available. Open Versions & sources to choose another recording.",
    );
  const request: "auto" | "server" | "original" =
    preference === "server"
      ? "server"
      : preference === "original"
        ? "original"
        : state.faults.server
          ? "original"
          : state.faults.original
            ? "server"
            : "auto";
  const input = {
    preference,
    request,
    remembered:
      (preference === "server" || preference === "original") &&
      skipStream({ request: preference, recentFailure, download, fault }),
    deviceCopy: !!download && !fault,
    device: (preference === "auto" || preference === "device") && !fault,
    expected: (request === "server"
      ? "server"
      : request === "original"
        ? track.sourceType === "torbox"
          ? "torbox"
          : "remote"
        : server
          ? "server"
          : track.sourceType === "torbox"
            ? "torbox"
            : "remote") as Shown,
    bad: (source: string | null) =>
      source === "device"
        ? !!fault
        : source === "server"
          ? !!state.faults.server
          : !!state.faults.original,
  };
  // `load` from `const local = ...` to the location request; autoplay on.
  const load = (complete: boolean): LegacyLoad => {
    const local = input.device || input.remembered ? complete : false;
    if (input.preference === "device" && !local)
      return {
        error:
          "This device copy is incomplete. Remove it and download it again, or choose another source.",
      };
    if (local)
      return {
        plays: "device",
        show: "device",
        notice: input.remembered
          ? input.preference === "original"
            ? "original"
            : "server"
          : null,
      };
    return {
      plays: "stream",
      query: input.request === "auto" ? "" : `?source=${input.request}`,
      show: input.expected,
      location: input.request,
      streamLoad:
        input.preference === "server" || input.preference === "original"
          ? { request: input.preference, deviceCopy: input.deviceCopy }
          : null,
    };
  };
  return {
    sourcesFromCache: skipping,
    result: {
      preference: input.preference,
      looksForDevice: input.device || input.remembered,
      complete: load(true),
      incomplete: load(false),
      faulty: {
        device: input.bad("device"),
        server: input.bad("server"),
        torbox: input.bad("torbox"),
        remote: input.bad("remote"),
        none: input.bad(null),
      },
    },
  };
}

// `recoverOnDevice` after a confirmed transport failure, with the download row
// and device fault read again at that moment: true switches to the device copy
// when its bytes are complete.
export function legacyRecovers(
  request: "server" | "original",
  download: object | undefined,
  fault: MediaFault | undefined,
) {
  return canFallBackToDevice(request, download, fault);
}

// Whether the location answer replaces the shown source.
export function legacyTakesLocation(report: {
  currentLoad: boolean;
  playingDeviceCopy: boolean;
  workerReported: boolean;
}) {
  return report.currentLoad && !report.playingDeviceCopy && !report.workerReported;
}

// Whether the service worker's `sonder:media-source` message (already checked
// to come from the controller with that type) replaces the shown source.
export function legacyTakesWorkerReport(report: {
  sameTrack: boolean;
  source: unknown;
  playingDeviceCopy: boolean;
}) {
  return (
    report.sameTrack &&
    ["device", "server", "torbox", "remote"].includes(report.source as string) &&
    !report.playingDeviceCopy
  );
}
